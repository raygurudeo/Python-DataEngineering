# <<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<< Operators >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>
# Arithmetic Operators
# Used for mathematical calculations.

# <<<<<<<<<<<<<<<<<<<< Operator	Meaning	Example	Output >>>>>>>>>>>>>>>>>>>>>>
# +	  Addition	     10 + 5	15
# -	  Subtraction	 10 - 5	5
# *	  Multiplication 10 * 5	50
# /	  Division (float result)	        10 / 3	3.333...
# //  Floor Division (integer result)	10 // 3	3
# %	  Modulus (remainder)	            10 % 3	1
# **  Exponent (power)	                2 ** 3	8

# Comparison Operators
# Used to compare values (result is always True or False).

# <<<<<<<<<<<<<<<<<< Operator	Meaning	Example	Output >>>>>>>>>>>>>>>>>>>>>
# ==	Equal to	      5 == 5	True
# !=	Not equal to	  5 != 3	True
# >	    Greater than	  10 > 3	True
# <	    Less than	      2 < 5	    True
# >=	Greater or equal  5 >= 5	True
# <=	Less or equal	  3 <= 4	True


# <<<<<<<<<<<<<<<< Logical Operators >>>>>>>>>>>>>>>>>>>>>>>>>>>>
# Used to combine conditions.

# and	True if both are True	        (5 > 3 and 10 > 5)	True
# or	True if at least one is True	(5 > 3 or 10 < 5)	True
# not	Negates the condition	        not(5 > 3)	False
print(not(5>3))